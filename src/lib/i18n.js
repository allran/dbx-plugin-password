export function resolveMessages(locale) {
  const raw = String(locale || "en").toLowerCase();
  if (raw.startsWith("zh")) return messages.zh;
  return messages.en;
}

export function displayGroupName(group, text) {
  if (!group) return text.defaultGroup;
  if (group.id === DEFAULT_GROUP_ID) return text.defaultGroup;
  return group.name || text.defaultGroup;
}
